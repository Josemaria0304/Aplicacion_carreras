function computeStats(
  driver: RawDriver,
  all: { id: string; points: number; wins: number; podiums: number }[],
): Driver['stats'] {
  const points = driver.results.reduce<number>((sum, result, index) => {
    if (typeof result !== 'number') return sum
    const base = POINTS_SCALE[result - 1] ?? 0
    const bonus = driver.fastestLapRounds.includes(index + 1) ? 1 : 0
    return sum + base + bonus
  }, 0)
  const wins = driver.results.filter((result) => result === 1).length
  const podiums = driver.results.filter(
    (result) => typeof result === 'number' && result <= 3,
  ).length
  const position =
    all
      .slice()
      .sort((a, b) => b.points - a.points || b.wins - a.wins || b.podiums - a.podiums)
      .findIndex((entry) => entry.id === driver.id) + 1

  return {
    starts: driver.results.length,
    wins,
    podiums,
    poles: driver.poles,
    fastestLaps: driver.fastestLapRounds.length,
    titles: driver.titles,
    points,
    position,
  }
}

export const driverPoints = rawDrivers.map((driver) => ({
  id: driver.id,
  points: driver.results.reduce<number>((sum, result, index) => {
    if (typeof result !== 'number') return sum
    return (
      sum +
      (POINTS_SCALE[result - 1] ?? 0) +
      (driver.fastestLapRounds.includes(index + 1) ? 1 : 0)
    )
  }, 0),
  wins: driver.results.filter((result) => result === 1).length,
  podiums: driver.results.filter(
    (result) => typeof result === 'number' && result <= 3,
  ).length,
}))

