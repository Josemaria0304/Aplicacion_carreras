function buildVehicle(base: VehicleBase): Vehicle {
  const docs = [
    {
      name: 'Homologación FIA',
      expires: '31 DIC 2027',
      status: 'valid' as const,
    },
    {
      name: 'Seguro deportivo',
      expires: '31 DIC 2026',
      status: 'valid' as const,
    },
    {
      name: 'Pasaporte técnico',
      expires: base.status === 'observed' ? '30 JUN 2026' : '31 MAR 2027',
      status: base.status === 'observed' ? ('expiring' as const) : ('valid' as const),
    },
  ]
  const checklist: VehicleChecklistItem[] = checklistLabels.map((label, index) => ({
    label,
    ok: base.status === 'approved' ? true : base.status === 'pending' ? index > 2 : index !== 5,
  }))
  return { ...base, documents: docs, checklist }
}

